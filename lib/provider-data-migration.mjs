export function legacyCandidates() {
  const { summary, rows } = inspectLegacyProviders();
  if (summary.validRecords !== 66 || summary.rejectedRecords || summary.countsByCategory.ems !== 46
    || summary.countsByCategory.domicile !== 12 || summary.countsByCategory.residence !== 8) {
    throw new Error("One-time migration requires the reviewed 66-record legacy batch");
  }
  for (const { provider: p, source, serviceAreas } of rows) {
    if (p.status !== "active" || p.verification_status !== "unverified" || p.is_published !== false
      || p.country_code !== "CH" || serviceAreas.length || Object.keys(p.attributes).length
      || ["subtypes", "service_codes", "language_codes"].some((key) => p[key].length)
      || ["last_reviewed_at", "canton_code", "municipality_id", "street", "house_number", "latitude", "longitude",
        "phone", "email", "website", "description"].some((key) => p[key] !== null)
      || source.source_type !== "legacy" || source.external_record_id !== p.legacy_id
      || source.source_url !== null || source.retrieved_at !== null || source.reviewed_at !== null
      || Object.keys(p).sort().join() !== Object.keys(providerTypes).sort().join()
      || Object.keys(source).sort().join() !== Object.keys(sourceTypes).sort().join()) {
      throw new Error("Unsafe or changed legacy candidate contract; review before generating");
    }
  }
  return rows.map(({ provider, source }) => ({ provider, source }));
}

const header = `-- GENERATED by scripts/generate-provider-data-migration.mjs. Do not hand-edit.
-- One-time legacy preservation: 66 providers, 66 private legacy sources (46/12/8).
-- Unverified and unpublished. active means directory lifecycle, not real-world operation.
-- Execution requires separate production authorization. Generation never connects to a database.
`;

function staging(batch) {
  return `CREATE TEMP TABLE lia_legacy_batch (
  legacy_id text PRIMARY KEY, slug text NOT NULL UNIQUE, provider jsonb NOT NULL, source jsonb NOT NULL
) ON COMMIT DROP;
INSERT INTO lia_legacy_batch
SELECT item->'provider'->>'legacy_id', item->'provider'->>'slug', item->'provider', item->'source'
FROM jsonb_array_elements(${jsonSql(batch)}) item;
`;
}

const tables = ["providers", "provider_sources", "provider_service_areas", "municipalities"];
const existenceGuard = `DO $tables$
DECLARE table_name text;
BEGIN
  FOREACH table_name IN ARRAY ARRAY['providers','provider_sources','provider_service_areas','municipalities'] LOOP
    IF to_regclass('public.' || table_name) IS NULL THEN
      RAISE EXCEPTION 'Missing Phase 1 table or RLS: %', table_name;
    END IF;
  END LOOP;
END $tables$;
`;
const schemaGuard = `DO $prerequisites$
DECLARE table_name text; requirement record; actual_type text; expression text; allowed text; accepts boolean;
BEGIN
  FOREACH table_name IN ARRAY ARRAY['providers','provider_sources','provider_service_areas','municipalities'] LOOP
    IF NOT EXISTS (SELECT FROM pg_class WHERE oid = to_regclass('public.' || table_name)
      AND relkind = 'r' AND relrowsecurity) THEN
      RAISE EXCEPTION 'Missing Phase 1 table or RLS: %', table_name;
    END IF;
  END LOOP;
  IF (SELECT count(*) FROM pg_roles WHERE rolname IN ('anon','authenticated') AND NOT rolsuper AND NOT rolbypassrls) <> 2 THEN
    RAISE EXCEPTION 'Missing or unsafe client roles';
  END IF;
  FOR requirement IN SELECT * FROM jsonb_to_recordset(${jsonSql([
    ...Object.entries({ id: "uuid", ...providerTypes }).map(([column, type]) => ({ table_name: "providers", column, type })),
    ...Object.entries({ id: "uuid", provider_id: "uuid", ...sourceTypes }).map(([column, type]) => ({ table_name: "provider_sources", column, type })),
  ])}) AS x(table_name text, "column" text, type text) LOOP
    SELECT format_type(atttypid, atttypmod) INTO actual_type FROM pg_attribute
      WHERE attrelid = to_regclass('public.' || requirement.table_name)
        AND attname = requirement."column" AND attnum > 0 AND NOT attisdropped;
    IF actual_type IS DISTINCT FROM requirement.type THEN
      RAISE EXCEPTION 'Incompatible column: %.%', requirement.table_name, requirement."column";
    END IF;
  END LOOP;
  FOREACH table_name IN ARRAY ARRAY['providers','provider_sources'] LOOP
    IF NOT EXISTS (SELECT FROM pg_attribute a JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
      WHERE a.attrelid = to_regclass('public.' || table_name) AND a.attname = 'id' AND a.attnotnull)
      OR NOT EXISTS (SELECT FROM pg_constraint c JOIN pg_attribute a ON a.attrelid = c.conrelid
        WHERE c.conrelid = to_regclass('public.' || table_name) AND a.attname = 'id'
          AND c.contype = 'p' AND c.conkey = ARRAY[a.attnum]) THEN
      RAISE EXCEPTION 'Missing generated UUID primary key: %', table_name;
    END IF;
  END LOOP;
  FOR requirement IN SELECT * FROM (VALUES
    ('primary_type', ARRAY['ems','domicile','residence']),
    ('status', ARRAY['active','inactive','archived']),
    ('verification_status', ARRAY['unverified','partially_verified','verified','stale'])
  ) AS x(column_name, values) LOOP
    SELECT string_agg('(' || pg_get_expr(c.conbin, c.conrelid) || ')', ' AND ') INTO expression
      FROM pg_constraint c JOIN pg_attribute a ON a.attrelid = c.conrelid AND c.conkey = ARRAY[a.attnum]
      WHERE c.conrelid = 'public.providers'::regclass AND c.contype = 'c' AND c.convalidated
        AND a.attname = requirement.column_name AND a.attnotnull;
    IF expression IS NULL THEN RAISE EXCEPTION 'Missing validated state/type constraint: %', requirement.column_name; END IF;
    FOREACH allowed IN ARRAY requirement.values || ARRAY['__invalid_lia_value__'] LOOP
      EXECUTE format('SELECT %s FROM (SELECT $1::text AS %I) candidate', expression, requirement.column_name) INTO accepts USING allowed;
      IF accepts IS DISTINCT FROM (allowed <> '__invalid_lia_value__') THEN
        RAISE EXCEPTION 'Incompatible state/type constraint: %', requirement.column_name;
      END IF;
    END LOOP;
  END LOOP;
  FOREACH table_name IN ARRAY ARRAY['legacy_id','slug'] LOOP
    IF NOT EXISTS (SELECT FROM pg_constraint c JOIN pg_attribute a ON a.attrelid = c.conrelid
      WHERE c.conrelid = 'public.providers'::regclass AND c.contype = 'u'
        AND a.attname = table_name AND c.conkey = ARRAY[a.attnum]) THEN
      RAISE EXCEPTION 'Missing provider identity uniqueness: %', table_name;
    END IF;
  END LOOP;
END $prerequisites$;
`;

function leadsSnapshot(variable) {
  return `IF to_regclass('public.leads') IS NULL THEN ${variable} := '{"exists":false}'::jsonb;
  ELSE
    EXECUTE 'SELECT count(*) FROM public.leads' INTO lead_count;
    SELECT jsonb_build_object('exists', true, 'rows', lead_count,
      'schema', n.nspname, 'columns', (SELECT count(*) FROM pg_attribute WHERE attrelid = c.oid AND attnum > 0 AND NOT attisdropped),
      'columnDefinitions', (SELECT jsonb_agg(jsonb_build_array(a.attname, format_type(a.atttypid,a.atttypmod), a.attnotnull,
        pg_get_expr(d.adbin,d.adrelid)) ORDER BY a.attnum) FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE a.attrelid = c.oid AND a.attnum > 0 AND NOT a.attisdropped),
      'policies', (SELECT count(*) FROM pg_policy WHERE polrelid = c.oid),
      'rls', c.relrowsecurity, 'forceRls', c.relforcerowsecurity) INTO ${variable}
      FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace WHERE c.oid = 'public.leads'::regclass;
  END IF;`;
}

const snapshot = `CREATE TEMP TABLE lia_legacy_untouched (name text PRIMARY KEY, snapshot jsonb) ON COMMIT DROP;
DO $snapshot$
DECLARE lead_count bigint; state jsonb;
BEGIN
  IF to_regclass('public.leads') IS NOT NULL THEN LOCK TABLE public.leads IN SHARE MODE; END IF;
  ${leadsSnapshot("state")}
  INSERT INTO lia_legacy_untouched VALUES ('leads', state);
  INSERT INTO lia_legacy_untouched SELECT 'municipalities', coalesce(jsonb_agg(to_jsonb(m) ORDER BY id), '[]') FROM public.municipalities m;
END $snapshot$;
`;

const collisions = `DO $collisions$
BEGIN
  IF EXISTS (SELECT FROM public.providers p JOIN lia_legacy_batch b ON p.legacy_id = b.legacy_id) THEN
    RAISE EXCEPTION 'Legacy ID collision; one-time import refused';
  END IF;
  IF EXISTS (SELECT FROM public.providers p JOIN lia_legacy_batch b ON p.slug = b.slug) THEN
    RAISE EXCEPTION 'Slug collision; one-time import refused';
  END IF;
  -- Provider UUIDs do not exist yet: refuse this source identity on ANY existing provider.
  IF EXISTS (SELECT FROM public.provider_sources s JOIN lia_legacy_batch b
    ON s.source_type = b.source->>'source_type' AND s.source_name = b.source->>'source_name'
      AND s.external_record_id = b.source->>'external_record_id') THEN
    RAISE EXCEPTION 'Legacy provenance collision; one-time import refused';
  END IF;
END $collisions$;
`;

const inserts = `INSERT INTO public.providers (${Object.keys(providerTypes).join(", ")})
SELECT ${Object.keys(providerTypes).map((key) => `p.${key}`).join(", ")}
FROM lia_legacy_batch b CROSS JOIN LATERAL jsonb_populate_record(NULL::public.providers, b.provider) p;

-- Stable identity join, never row order; UUIDs are generated by PostgreSQL.
INSERT INTO public.provider_sources (provider_id, ${Object.keys(sourceTypes).join(", ")})
SELECT p.id, ${Object.keys(sourceTypes).map((key) => `s.${key}`).join(", ")}
FROM lia_legacy_batch b JOIN public.providers p ON p.legacy_id = b.legacy_id
CROSS JOIN LATERAL jsonb_populate_record(NULL::public.provider_sources, b.source) s;
`;

function verification(batch) {
  const ids = jsonSql(batch.map(({ provider }) => provider.legacy_id));
  return `DO $verify$
DECLARE lead_count bigint; state jsonb;
BEGIN
  IF (SELECT count(*) FROM lia_legacy_batch) <> 66
    OR (SELECT count(*) FROM public.providers p JOIN lia_legacy_batch b ON p.legacy_id = b.legacy_id) <> 66
    OR EXISTS (SELECT FROM lia_legacy_batch b LEFT JOIN public.providers p ON p.legacy_id = b.legacy_id
      WHERE p.id IS NULL OR to_jsonb(p) - ARRAY['id','created_at','updated_at'] IS DISTINCT FROM b.provider)
    OR (SELECT count(*) FROM public.providers p JOIN lia_legacy_batch b ON p.legacy_id = b.legacy_id WHERE primary_type = 'ems') <> 46
    OR (SELECT count(*) FROM public.providers p JOIN lia_legacy_batch b ON p.legacy_id = b.legacy_id WHERE primary_type = 'domicile') <> 12
    OR (SELECT count(*) FROM public.providers p JOIN lia_legacy_batch b ON p.legacy_id = b.legacy_id WHERE primary_type = 'residence') <> 8
    OR EXISTS (SELECT FROM public.provider_service_areas a JOIN public.providers p ON p.id = a.provider_id JOIN lia_legacy_batch b ON b.legacy_id = p.legacy_id)
    OR EXISTS (SELECT FROM lia_legacy_batch b JOIN public.providers p ON p.legacy_id = b.legacy_id
      WHERE (SELECT count(*) FROM public.provider_sources s WHERE s.provider_id = p.id
        AND s.source_type = b.source->>'source_type' AND s.source_name = b.source->>'source_name'
        AND s.external_record_id = b.source->>'external_record_id') <> 1)
    OR EXISTS (SELECT FROM lia_legacy_batch b JOIN public.providers p ON p.legacy_id = b.legacy_id
      JOIN public.provider_sources s ON s.provider_id = p.id AND s.source_type = b.source->>'source_type'
        AND s.source_name = b.source->>'source_name' AND s.external_record_id = b.source->>'external_record_id'
      WHERE to_jsonb(s) - ARRAY['id','provider_id','created_at'] IS DISTINCT FROM b.source) THEN
    RAISE EXCEPTION 'Legacy batch identity, safe defaults or provenance mismatch';
  END IF;
  ${leadsSnapshot("state")}
  IF state IS DISTINCT FROM (SELECT snapshot FROM lia_legacy_untouched WHERE name = 'leads') THEN
    RAISE EXCEPTION 'Leads count/schema/policies/RLS changed';
  END IF;
  IF (SELECT coalesce(jsonb_agg(to_jsonb(m) ORDER BY id), '[]') FROM public.municipalities m)
    IS DISTINCT FROM (SELECT snapshot FROM lia_legacy_untouched WHERE name = 'municipalities') THEN
    RAISE EXCEPTION 'Municipalities changed';
  END IF;
END $verify$;
${["anon", "authenticated"].map((role) => `SET LOCAL ROLE ${role};
DO $visibility$
BEGIN
  IF EXISTS (SELECT FROM public.providers WHERE legacy_id IN (SELECT jsonb_array_elements_text(${ids}))) THEN
    RAISE EXCEPTION '${role} can see legacy providers';
  END IF;
  IF has_table_privilege(current_user, 'public.provider_sources', 'SELECT')
    OR has_any_column_privilege(current_user, 'public.provider_sources', 'SELECT') THEN
    RAISE EXCEPTION '${role} has access to private sources';
  END IF;
  BEGIN
    PERFORM 1 FROM public.provider_sources LIMIT 1;
    RAISE EXCEPTION '${role} can query private sources';
  EXCEPTION WHEN insufficient_privilege THEN NULL;
  END;
END $visibility$;
RESET ROLE;
`).join("")}
SELECT jsonb_build_object('scope','legacy-batch','providers',66,'sources',66,'ems',46,'domicile',12,'residence',8,
  'unverified',66,'published',0,'nullCantons',66,'serviceAreas',0,'services',0,'languages',0,
  'anonVisible',0,'authenticatedVisible',0,'municipalitiesUnchanged',true,
  'leadsUnchanged',true,'leadsSnapshot',(SELECT snapshot FROM lia_legacy_untouched WHERE name = 'leads'));
`;
}

export function renderProviderDataSql({ verifyOnly = false } = {}) {
  const batch = legacyCandidates();
  return header + (verifyOnly ? "-- Verification only: no persistent writes; always ROLLBACK.\n" : "-- One-time import: a second execution must fail on batch collisions.\n")
    + "BEGIN;\nSET LOCAL lock_timeout = '10s';\nSET LOCAL statement_timeout = '60s';\nSET LOCAL search_path = pg_catalog, public;\n"
    + existenceGuard
    + `LOCK TABLE ${tables.map((name) => `public.${name}`).join(", ")} IN ${verifyOnly ? "SHARE" : "SHARE ROW EXCLUSIVE"} MODE;\n`
    + schemaGuard + staging(batch) + snapshot + (verifyOnly ? "" : collisions + inserts) + verification(batch)
    + (verifyOnly ? "ROLLBACK;\n" : "COMMIT;\n");
}
